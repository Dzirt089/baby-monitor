namespace BabyMonitor.Domain.Devices;

/// <summary>
/// Роль устройства в сеансе наблюдения. Роли асимметричны: детское устройство
/// захватывает и передаёт звук, родительское — только принимает и воспроизводит.
/// </summary>
public enum DeviceRole
{
    /// <summary>
    /// Роль не задана. Значение по умолчанию не должно означать включение микрофона:
    /// default(DeviceRole) обязан приводить к отказу, а не к роли Child.
    /// </summary>
    Unknown = 0,

    /// <summary>Детское устройство: работает микрофон, локального воспроизведения нет.</summary>
    Child = 1,

    /// <summary>Родительское устройство: работает воспроизведение, микрофон не используется.</summary>
    Parent = 2
}
